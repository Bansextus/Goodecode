"use strict";
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const {execFileSync} = require('child_process');
const {safeRelativePath, buildPackage} = require('../src/project');
const VERSION = '2.0.0-beta.1';
const hash = data => crypto.createHash('sha256').update(data).digest('hex');
function file(root, relative) {
 if (!safeRelativePath(relative)) throw Error(`Unsafe mod path: ${relative}`);
 const base=fs.realpathSync(root), candidate=path.join(base, relative);
 let current=base;
 for(const part of relative.split('/')) {
  current=path.join(current,part);
  if(fs.lstatSync(current).isSymbolicLink()) throw Error(`Mod symlink is forbidden: ${relative}`);
 }
 if(!fs.statSync(candidate).isFile() || fs.statSync(candidate).size>5*1024*1024) throw Error(`Invalid mod file: ${relative}`);
 return candidate;
}
function manifest(root) {
 const m=JSON.parse(fs.readFileSync(file(root,'goode.mod.json')));
 if(m.schemaVersion!==1 || m.sdkVersion!==VERSION || m.cortexCompatibility!=='v5-native-screen-1') throw Error('Unsupported native mod SDK/Cortex version. Install matching Goodecode 2 beta tooling.');
 if(!/^[a-z][a-z0-9.-]{2,79}$/.test(m.id)) throw Error('Invalid mod ID.');
 if(m.renderer?.abiVersion!==1 || !['c','cpp'].includes(m.renderer?.language)) throw Error('Native renderer requires screen ABI 1 and a C/C++ entrypoint. Other languages must expose the C ABI through a supported toolchain adapter.');
 if(!m.renderer.entry.startsWith('renderer/') || !m.renderer.entry.endsWith('.'+m.renderer.language)) throw Error('Renderer must be a renderer/*.c or *.cpp source file.');
 file(root,m.renderer.entry);
 if(!['python','javascript','typescript','json'].includes(m.adapter?.language)) throw Error('Unknown language adapter. Emit instruction JSON and use the json adapter for other languages.');
 if(!m.adapter.entry.startsWith('authoring/')) throw Error('Authoring source must be under authoring/.');
 file(root,m.adapter.entry);
 const lock=JSON.parse(fs.readFileSync(file(root,'goode.lock.json')));
 if(lock.sdk!==VERSION || lock.screenABI!==1 || lock.instructionSchema!==1 || Object.keys(lock.dependencies||{}).length) throw Error('Unsupported dependency lock. Beta 1 requires a dependency-free native renderer.');
 return m;
}
const declarations=new Set(['motor','motor_group','pneumatic','imu','drivetrain_ports','drive_mode']);
const operations=new Set(['status','wait_ms','sleep_ms','drive_for','turn_for','turn_to_heading','run_motor','stop','motor_group_command','pneumatic_on','pneumatic_off','pneumatic_toggle','tank_drive','arcade_drive','bind_motor_group','bind_button_sequence']);
function validateIR(p) {
 if(p.schemaVersion!==1 || typeof p.name!=='string' || !p.name.trim() || p.name.length>80) throw Error('Invalid instruction document schema/name.');
 for(const section of ['configuration','autonomous','driver']) {
  if(!Array.isArray(p[section]) || p[section].length>2048) throw Error(`Invalid instruction section: ${section}`);
  for(const c of p[section]) {
   if(!(section==='configuration'?declarations:operations).has(c.op) || !c.args || Array.isArray(c.args) || typeof c.args!=='object') throw Error(`Unsupported instruction: ${c.op}`);
   if(Object.keys(c.args).some(k=>!/^[_a-zA-Z][_a-zA-Z0-9]*$/.test(k))) throw Error('Invalid instruction argument name.');
   const valid=v=>v===null||typeof v==='string'||typeof v==='boolean'||(typeof v==='number'&&Number.isFinite(v))||(Array.isArray(v)&&v.every(valid));
   if(c.positional!==undefined && (!Array.isArray(c.positional)||!c.positional.every(valid))) throw Error('Invalid positional arguments.');
   if(!Object.values(c.args).every(valid)) throw Error('Arguments must be finite JSON literals or arrays.');
  }
 }
 return p;
}
const py=v=>v===null?'None':v===true?'True':v===false?'False':Array.isArray(v)?`[${v.map(py).join(', ')}]`:JSON.stringify(v);
function lower(p) {
 validateIR(p);
 const calls=rows=>rows.length?rows.map(c=>'    ctx.'+c.op+'('+[...(c.positional||[]).map(py),...Object.entries(c.args).map(([k,v])=>`${k}=${py(v)}`)].join(', ')+')').join('\n'):'    pass';
 return `# @goodecode.schema: 2\n# Generated by Goodecode ${VERSION}; edit authoring source, then regenerate.\ndef initialize(ctx):\n    ctx.project_title(${py(p.name)})\n    configure_robot(ctx)\n    configure_programs(ctx)\n\ndef configure_robot(ctx):\n${calls(p.configuration)}\n\ndef configure_programs(ctx):\n    ctx.program_profile(kind="practice", name=${py(p.name+' Practice')}, slot=1, auton="Main", autonomous="autonomous", driver_control="driver", brain_screen="screen", allow_auton_selection=True, allow_test_actions=True)\n    ctx.program_profile(kind="competition", name=${py(p.name+' Competition')}, slot=2, auton="Main", autonomous="autonomous", driver_control="driver", brain_screen="screen", allow_auton_selection=False, allow_test_actions=False)\n    ctx.auton_routine(name="Main", slot=1, callback="autonomous")\n\ndef autonomous(ctx):\n${calls(p.autonomous)}\n\ndef driver(ctx):\n${calls(p.driver)}\n\ndef screen(ctx):\n    ctx.screen_page(name="Native Mod", role="practice")\n    ctx.title(${py('MODDED: '+p.name)})\n`;
}
function generate(root) {
 const m=manifest(root), entry=file(root,m.adapter.entry);
 const node=process.versions.electron ? 'node' : process.execPath;
 const runners={python:['python3',['-I',entry]],javascript:[node,[entry]],typescript:[node,[entry]]};
 let data;
 if(m.adapter.language==='json') data=fs.readFileSync(entry,'utf8');
 else {
  const [cmd,args]=runners[m.adapter.language];
  // Explicit trusted-workspace operation, never run as part of import/validation.
  data=execFileSync(cmd,args,{cwd:root,timeout:15000,maxBuffer:2*1024*1024,encoding:'utf8',shell:false});
 }
 const ir=validateIR(JSON.parse(data));
 fs.mkdirSync(path.join(root,'src'),{recursive:true});
 fs.writeFileSync(path.join(root,'src/main.goode.py'),lower(ir));
 fs.writeFileSync(path.join(root,'goode.instructions.json'),JSON.stringify(ir,null,2)+'\n');
 fs.writeFileSync(path.join(root,'goode.generated.json'),JSON.stringify({adapterHash:hash(fs.readFileSync(entry)),instructionHash:hash(fs.readFileSync(path.join(root,'goode.instructions.json'))),sourceHash:hash(fs.readFileSync(path.join(root,'src/main.goode.py')))},null,2)+'\n');
 return validate(root);
}
function validate(root) {
 const m=manifest(root), ir=validateIR(JSON.parse(fs.readFileSync(file(root,'goode.instructions.json'))));
 const receipt=JSON.parse(fs.readFileSync(file(root,'goode.generated.json')));
 const source=fs.readFileSync(file(root,'src/main.goode.py'),'utf8');
 if(source!==lower(ir) || receipt.sourceHash!==hash(source) || receipt.adapterHash!==hash(fs.readFileSync(file(root,m.adapter.entry))) || receipt.instructionHash!==hash(fs.readFileSync(file(root,'goode.instructions.json')))) throw Error('Generated instructions are stale. Run Generate in a trusted workspace before exporting.');
 return m;
}
function create(root) {
 if(fs.existsSync(root) && fs.readdirSync(root).length) throw Error('Create Mod Project needs an empty directory; existing projects are never overwritten.');
 fs.cpSync(path.join(__dirname,'examples/dashboard'),root,{recursive:true,errorOnExist:true});
 return root;
}
function exportMod(root,outputPath) {
 validate(root);
 return buildPackage({root,outputPath,extensionVersion:VERSION,modded:true});
}
module.exports={VERSION,file,manifest,validateIR,lower,generate,validate,create,exportMod};
